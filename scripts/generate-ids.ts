// Writes src/schemas/generated/ids.ts from data/*.yaml, so task, lever and question ids are
// closed enums: a sealed link naming a task that no longer exists fails parsing, not a lookup
// deep inside an engine (D31). Run with `npm run generate:ids` after editing the data.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

import { format, resolveConfig } from 'prettier';

import type { DataDocuments } from '@/schemas/data/data-files';
import { createKnowledgeRepository, readFromDirectory } from '@/server/knowledge/repository';

export const IDS_PATH = join(process.cwd(), 'src', 'schemas', 'generated', 'ids.ts');
export const DATA_DIRECTORY = join(process.cwd(), 'data');

function enumBlock(constName: string, typeName: string, source: string, ids: readonly string[]) {
  return [
    `// From ${source}.`,
    `export const ${constName} = ${JSON.stringify(ids)} as const;`,
    `export const ${typeName} = z.enum(${constName});`,
    `export type ${typeName} = z.infer<typeof ${typeName}>;`,
  ].join('\n');
}

/** The exact text of ids.ts for these documents, formatted as the repository formats code. */
export async function renderIds(documents: DataDocuments): Promise<string> {
  const text = [
    '// Generated by scripts/generate-ids.ts from data/*.yaml; edit the data, then run',
    '// `npm run generate:ids`. CI fails when this file and the data disagree.',
    '',
    "import { z } from 'zod';",
    '',
    enumBlock(
      'taskIds',
      'TaskId',
      'data/tasks.yaml',
      documents.tasks.tasks.map((task) => task.id),
    ),
    '',
    enumBlock(
      'leverIds',
      'LeverId',
      'data/levers.yaml',
      documents.levers.levers.map((lever) => lever.id),
    ),
    '',
    enumBlock(
      'questionIds',
      'QuestionId',
      'data/vendor-questions.yaml',
      documents.vendorQuestions.questions.map((question) => question.id),
    ),
    '',
  ].join('\n');
  const options = await resolveConfig(IDS_PATH);
  return format(text, { ...options, filepath: IDS_PATH });
}

export function loadValidatedData(): DataDocuments {
  return createKnowledgeRepository(readFromDirectory(DATA_DIRECTORY)).all();
}

async function main(): Promise<void> {
  writeFileSync(IDS_PATH, await renderIds(loadValidatedData()), 'utf8');
  console.log(`Wrote ${IDS_PATH}`);
}

// Imported by validate-data.ts for renderIds; only writes when run as the entry point.
const entry = process.argv[1];
if (entry !== undefined && pathToFileURL(entry).href === import.meta.url) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
